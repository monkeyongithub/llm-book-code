"""展示八类提示方法的文字结构，便于与同节独立示例对照。

本文件只生成提示，不执行模型推理、搜索、投票或事实核验。
"""


# Step1、为各方法定义可直接对照的提示模板
PROMPTS = {
    # T1、思维链：要求给出可核对的解题步骤。
    "T1 思维链": "请解决以下问题，给出关键计算步骤和答案：{question}",
    # T2、思维树：扩展多个候选，再评价与选择。
    "T2 思维树": "请提出多个解法分支，依据题目约束评价各分支，再选择可行方案：{question}",
    # T3、自我一致性：实际应用需多次采样，提取最终答案后投票。
    "T3 自我一致性": "请独立解决以下问题，并以‘答案：’标明最终结果：{question}",
    # T4、反思：将初稿、问题和评价标准一起交给修订步骤。
    "T4 反思": "请先回答，再检查答案是否符合题目条件；发现错误时修订：{question}",
    # T5、专家提示：选择相关视角，再汇总观点。
    "T5 专家提示": "请从与问题相关的不同专业视角分析，并汇总共识和分歧：{question}",
    # T6、链式提示：将上一组件的结果传递给下一组件。
    "T6 链式提示": "请将任务分成可顺序执行的子任务，明确每一步传给下一步的信息：{question}",
    # T7、输出约束：格式约束仍需应用程序验证。
    "T7 输出约束": "请仅用 JSON 对象回答，包含 answer 和 evidence 两个字段；无依据时说明：{question}",
    # T8、自动提示工程：候选需在相同验证任务上评分。
    "T8 自动提示工程": "请为以下任务设计三种不同提示，明确各自适用条件：{question}",
}


# Step2、代入同一任务，观察不同方法如何组织请求
if __name__ == "__main__":
    question = "3 本书共 18 元，5 本同价的书需要多少钱？"
    for name, template in PROMPTS.items():
        print(f"\n{name}\n{template.format(question=question)}")
